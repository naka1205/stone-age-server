// shared/rules/config.h —— L3 的运行时配置
//
// ★★ 本文件存在的理由是 D7:「8.0 单基线,**不迁移宏,以运行时配置替代**」。
//    ⇒ 凡是原版靠 `#ifdef` 切换的玩法差异,在这里成为一个字段;
//      IDL 与 L3 里**不得出现任何条件编译**(02 §1.1 规则 4)。
//
// ⚠️ 但**不是所有宏都变成配置**。判据:
//    · 决策登记表裁定「照抄 + 留开关」的 → 是配置(如 DR-BT1)
//    · D7 裁定 8.0 单基线、另一形状不实现的 → **不是配置,是常量**
//      (如 `_BATTLE_NEWPOWER`,见 constants.h 的 kDefenseCoefNewPower)
//    ⇒ 把后者也做成开关,等于把"已经关掉的后路"重新打开。

#ifndef SA_SHARED_RULES_CONFIG_H
#define SA_SHARED_RULES_CONFIG_H

namespace sa::rules {

struct RulesConfig {
  // ── DR-BT1:空手多段连击各段全额 ──────────────────────────────
  //
  // ✅ 裁定 = **照抄**,默认 true。
  // 量化:LUCK 上限 25 ⇒ 触发上限 3.5%、**期望段数 1.31** ⇒ 是低频机制不是主流打法。
  // ★ 决定性依据:拳套走 `gDamageDiv = attack_max`(总伤不变、分摊到多段)而空手保持 1.0
  //   —— **拳套那行是显式添加的补丁**,若开发者认为多段都该分摊,不会只为拳套写一行
  //   ⇒ 空手是差别对待,不是疏漏。
  // ⚠️ 留开关是因为「上线后实测失衡可关」,**默认必须按原版**。
  bool unarmed_multihit_full_damage = true;

  // ── 全局伤害系数(原 getDamageCalc())────────────────────────
  //
  // ★★ 默认值是 **70,不是 100**:
  //     csa8.0/setup.cf     未赋值 ⇒ 走 getter 兜底 = 70
  //     StoneAge/gmsv       70
  //     stoneage85          85
  // ⇒ **8.0 投产下,全部物理伤害统一乘 0.70。**
  // ⚠️ 这条极易被当成"没配置就是 100"而写错,后果是全局伤害偏高 43%。
  int damage_calc_percent = 70;

  // ── 全局回避修正(原 gBattleDuckModyfy)──────────────────────
  // 直接加进回避率 per。原版是全局变量,新实现改配置。
  int dodge_modifier = 0;

  // ── 敌人生成数上限(DR-WM2)──────────────────────────────────
  // ✅ 裁定 = 取 10(8.0),并**纳入正式配置项** —— 它不在原版的 295 参数字典里。
  int enemy_move_num = 10;

  // ── 视野半径(DR-WM1)────────────────────────────────────────
  //
  // ✅ 裁定 = **取 23**,客户端**跟随服务端**不独立设置。
  // ⚠️ 每次广播比取 20 多扫 88 格;且 `#define` 不进符号表 ⇒ 8.0 真值静态不可判定
  //   (00 §10.2 六项永久不可判定之一)⇒ 这是**选定**,不是**查明**。
  int sight_radius = 23;

  // ── 数值截断(DR-DT1)────────────────────────────────────────
  //
  // ✅ 裁定 = **浮点建模**,默认 false(按设计意图,不复刻 atoi 截断)。
  // 依据:1,053 行宠物模板中 **569 行(54.0%)** 受影响,且系数被乘以 (level−1)
  //      ⇒ **截断按等级累积**。11 张主表全扫只有这一列有小数。
  bool replicate_atoi_truncation = false;
};

}  // namespace sa::rules

#endif  // SA_SHARED_RULES_CONFIG_H
